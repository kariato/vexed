import { expect, test } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import type { FrameLocator, Page } from '@playwright/test'
const game = (page: Page) => page.frameLocator('iframe[title="Vexed game"]')
async function ready(frame: FrameLocator) {
  await expect(frame.getByRole('grid')).toBeVisible()
  await expect(frame.getByText('Saved on this device', { exact: true })).toBeVisible()
}
async function choose(frame: FrameLocator, id: string) {
  await frame.locator('details.pack-switcher > summary').click()
  await frame.getByLabel('Puzzle pack', { exact: true }).selectOption(id)
  await ready(frame)
}
test('extracted ZIP runs in a nested iframe, restores pack saves and plays solutions', async ({ page }) => {
  const bad: string[] = []
  page.on('pageerror', error => bad.push(error.message))
  page.on('response', response => { if (response.status() >= 400) bad.push(response.url() + ': ' + response.status()) })
  await page.goto('/embed.html')
  const frame = game(page); await ready(frame)
  await frame.locator('#cell-4-2').click(); await frame.locator('#cell-5-2').click()
  await expect(frame.locator('.stats dd').first()).toHaveText('1')
  await expect(frame.getByRole('grid')).toHaveAttribute('aria-busy', 'false')
  await expect(frame.getByText('Saved on this device', { exact: true })).toBeVisible()
  await frame.getByRole('button', { name: 'Restart', exact: true }).click()
  await frame.getByRole('dialog', { name: 'Confirm action', exact: true }).getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(frame.locator('.stats dd').first()).toHaveText('1')
  await choose(frame, 'variety-41-pack')
  await expect(frame.locator('.stats dd').first()).toHaveText('0')
  await frame.getByRole('button', { name: 'View solution', exact: true }).click()
  const confirmation = frame.getByRole('dialog', { name: 'Confirm action', exact: true })
  await expect(confirmation).toBeVisible()
  await confirmation.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(frame.getByLabel('Pack score')).toHaveText('0')
  await frame.getByRole('button', { name: 'View solution', exact: true }).click()
  await confirmation.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(frame.getByRole('dialog')).toBeVisible()
  await frame.getByRole('button', { name: 'Next step', exact: true }).click()
  await frame.getByRole('button', { name: 'Return to game', exact: true }).click()
  await expect(frame.getByLabel('Pack score')).toHaveText('+5')
  await expect(frame.getByText('Saved on this device', { exact: true })).toBeVisible()
  await page.reload(); await ready(game(page))
  await expect(game(page).getByLabel('Puzzle pack', { exact: true })).toHaveValue('variety-41-pack')
  await expect(game(page).getByLabel('Pack score')).toHaveText('+5')
  await choose(game(page), 'classic')
  await expect(game(page).locator('.stats dd').first()).toHaveText('1')
  expect(bad).toEqual([])
})
test('installation opens GitHub Pages and this version registers no service worker', async ({ page, context }) => {
  await context.route('https://kariato.github.io/vexed/', route => route.fulfill({ contentType: 'text/html', body: '<h1>Installable app destination</h1>' }))
  await page.goto('/embed.html'); await ready(game(page))
  const frame = game(page)
  const link = frame.getByRole('link', { name: 'Open the installable Vexed app' })
  await expect(link).toHaveAttribute('href', 'https://kariato.github.io/vexed/')
  const popup = page.waitForEvent('popup')
  await link.click(); const installed = await popup
  await expect(installed).toHaveURL('https://kariato.github.io/vexed/'); await installed.close()
  expect(await page.evaluate(async () => (await navigator.serviceWorker.getRegistrations()).length)).toBe(0)
  await expect(frame.getByText(/Preparing offline|ready offline|Check for updates/)).toHaveCount(0)
  await expect(frame.getByRole('link', { name: 'Download application source & license' })).toHaveAttribute('href', './vexed-source.zip')
  await expect(frame.locator('link[rel="manifest"]')).toHaveCount(0)
  const source = await page.request.get('/html/12345/vexed-source.zip')
  expect(source.ok()).toBe(true)
  expect((await source.body()).subarray(0, 2).toString()).toBe('PK')
  await frame.locator('main').screenshot({ path: test.info().outputPath('itch-install-link.png') })
})
test('embedded game passes accessibility and fits the viewport', async ({ page }) => {
  await page.goto('/embed.html'); await ready(game(page))
  const frame = game(page)
  await frame.locator('details.pack-switcher > summary').click()
  const result = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze()
  expect(result.violations.map(item => ({ id: item.id, nodes: item.nodes.map(node => node.target) }))).toEqual([])
  const width = await frame.locator('html').evaluate(element => ({ scroll: element.scrollWidth, client: element.clientWidth }))
  expect(width.scroll).toBeLessThanOrEqual(width.client)
})

test('blocked storage uses in-game confirmation before switching an unsaved pack', async ({ page }) => {
  await page.addInitScript(() => Object.defineProperty(window, 'indexedDB', { get() { throw new Error('Blocked') } }))
  await page.goto('/embed.html')
  const frame = game(page)
  await expect(frame.getByRole('grid')).toBeVisible()
  await frame.locator('details.pack-switcher > summary').click()
  await frame.getByLabel('Puzzle pack', { exact: true }).selectOption('classic-ii')
  await frame.getByRole('dialog', { name: 'Confirm action', exact: true }).getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(frame.getByLabel('Puzzle pack', { exact: true })).toHaveValue('classic')
  await frame.getByLabel('Puzzle pack', { exact: true }).selectOption('classic-ii')
  await frame.getByRole('dialog', { name: 'Confirm action', exact: true }).getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(frame.getByRole('grid')).toBeVisible()
  await expect(frame.getByLabel('Puzzle pack', { exact: true })).toHaveValue('classic-ii')
})
