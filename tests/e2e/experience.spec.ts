import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'
const grid = (page: Page) => page.locator('.game .board')
async function tap(page: Page, x: number, y: number) {
  await expect(grid(page)).toHaveAttribute('aria-busy', 'false')
  const cell = page.locator('#cell-' + x + '-' + y)
  if (!test.info().project.use.hasTouch) await cell.click(); else await cell.tap()
}
async function move(page: Page) { await tap(page, 4, 2); await tap(page, 5, 2); await expect(grid(page)).toHaveAttribute('aria-busy', 'false') }
async function board(page: Page) { return grid(page).getByRole('gridcell').evaluateAll(cells => cells.map(cell => cell.getAttribute('aria-label'))) }
test.beforeEach(async ({ page }) => { await page.goto('./'); await expect(grid(page)).toBeVisible() })
test('checkpoint, replay and undo preserve the exact player attempt', async ({ page }) => {
  await page.getByRole('button', { name: 'Memorize', exact: true }).click()
  await move(page)
  const before = await board(page)
  await page.getByRole('button', { name: 'Replay moves', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: 'Next step', exact: true }).click()
  await expect(dialog.getByRole('status')).toContainText('Step 1 of 1')
  await dialog.getByRole('button', { name: 'Return to game', exact: true }).click()
  expect(await board(page)).toEqual(before)
  await expect(page.locator('.stats dd').first()).toHaveText('1')
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(page.locator('.stats dd').first()).toHaveText('0')
  await move(page)
  await page.getByRole('button', { name: 'Recall', exact: true }).click()
  await expect(page.locator('.stats dd').first()).toHaveText('0')
  await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled()
})
test('solution cancellation is free; confirmed openings charge and restore player state', async ({ page }) => {
  await page.getByRole('button', { name: 'Memorize', exact: true }).click()
  await move(page)
  const before = await board(page)
  page.once('dialog', dialog => dialog.dismiss())
  await page.getByRole('button', { name: 'View solution', exact: true }).click()
  await expect(page.getByLabel('Pack score')).toHaveText('0')
  await expect(page.getByRole('button', { name: 'View solution', exact: true })).toBeEnabled()
  for (const score of ['+5', '+10']) {
    page.once('dialog', dialog => dialog.accept())
    await page.getByRole('button', { name: 'View solution', exact: true }).click()
    const dialog = page.getByRole('dialog')
    await expect(dialog).toBeVisible()
    await dialog.getByRole('button', { name: 'Play', exact: true }).click()
    await expect(dialog.getByRole('status')).toContainText('Solved')
    await dialog.getByRole('button', { name: 'Return to game', exact: true }).click()
    expect(await board(page)).toEqual(before)
    await expect(page.getByLabel('Pack score')).toHaveText(score)
    await expect(page.locator('.stats dd').first()).toHaveText('1')
  }
  await page.getByRole('button', { name: 'Recall', exact: true }).click()
  await expect(page.locator('.stats dd').first()).toHaveText('0')
  await expect(page.getByLabel('Pack score')).toHaveText('+10')
})
test('solving unlocks next level and makes at-par solution viewing free', async ({ page }) => {
  await expect(page.locator('select[aria-label="Go to level"] option[value="1"]')).toHaveJSProperty('disabled', true)
  for (const [x, y] of [[4, 2], [3, 5], [3, 2], [4, 2]]) { await tap(page, x!, y!); await tap(page, x! + 1, y!) }
  await expect(grid(page)).toHaveAttribute('aria-busy', 'false')
  await expect(page.locator('select[aria-label="Go to level"] option[value="1"]')).toHaveJSProperty('disabled', false)
  await page.getByRole('button', { name: 'View solution', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('button', { name: 'Return to game', exact: true }).click()
  await expect(page.getByLabel('Pack score')).toHaveText('0')
  await page.getByRole('button', { name: 'Next puzzle' }).click()
  await page.getByRole('button', { name: 'Replay previous', exact: true }).click()
  await expect(page.getByRole('dialog').getByRole('heading')).toHaveText('Your replay · Level 1')
  await page.getByRole('dialog').press('Escape')
  await expect(page.getByRole('heading', { name: 'Level 2', exact: true })).toBeVisible()
})
test('themes share game state, reduced motion skips animation, practice unlocks all', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.getByText('Settings', { exact: true }).click()
  await page.getByLabel('Appearance', { exact: true }).selectOption('modern')
  await expect(page.locator('main')).toHaveClass('theme-modern')
  await page.getByLabel('Practice: unlock all levels').check()
  await expect(page.locator('select[aria-label="Go to level"] option[value="58"]')).toHaveJSProperty('disabled', false)
  await move(page)
  const before = await board(page)
  await page.getByLabel('Appearance', { exact: true }).selectOption('classic')
  expect(await board(page)).toEqual(before)
  await expect(page.locator('.sprites')).toHaveCount(0)
  await page.getByLabel('Animations', { exact: true }).selectOption('off')
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(page.locator('.stats dd').first()).toHaveText('0')
})
test('bad solution data never opens a viewer or charges a penalty', async ({ page }) => {
  await page.route('**/packs/classic-solutions.json', route => route.fulfill({ contentType: 'application/json', body: '{"schemaVersion":99}' }))
  await page.getByRole('button', { name: 'View solution', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('No penalty was charged')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByLabel('Pack score')).toHaveText('0')
})
test('rapid input during resolution cannot double moves; reduced motion fast-forwards', async ({ page }) => {
  await page.clock.install({ time: new Date('2026-10-17T12:00:00Z') })
  await page.clock.pauseAt(new Date('2026-10-17T12:01:00Z'))
  await tap(page, 4, 2); await tap(page, 5, 2)
  for (const x of [3, 4]) { const box = (await page.locator('#cell-' + x + '-2').boundingBox())!; await page.mouse.click(box.x + box.width / 2, box.y + box.height / 2) }
  await expect(page.locator('.stats dd').first()).toHaveText('1')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.clock.runFor(20)
  await page.clock.resume()
  await expect(grid(page)).toHaveAttribute('aria-busy', 'false')
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(page.locator('.stats dd').first()).toHaveText('0')
})
